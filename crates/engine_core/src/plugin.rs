//! Расширение движка плагинами.

use crate::App;

/// Единица расширения движка.
///
/// Рендер, мир, генерация и базовый контент игры — плагины, собираемые в одном месте
/// (`client`). Мод в будущем подключается ровно так же: других способов расширения нет.
pub trait Plugin: 'static {
    /// Уникальное имя плагина. Повторная установка под тем же именем игнорируется.
    fn name(&self) -> &'static str;

    /// Зарегистрировать системы, ресурсы и сообщения плагина.
    fn build(&self, app: &mut App);
}
